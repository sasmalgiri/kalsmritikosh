}

/// Everything v179 holds for one case's briefs, read together.
public nonisolated struct CaseBriefLedger: Sendable, Equatable {
    public var briefs: [CaseBriefVersion] = []
    public var relevance: [CaseBriefRelevance] = []
    public var briefings: [CaseBriefing] = []
    /// The case's content fence now (brief writes left out), to tell whether a brief was written before later changes.
    public var currentFence: String = ""
    public init() {}
    /// The versions of one anchor's brief, newest first.
    public func versions(of anchor: CaseMapNodeID) -> [CaseBriefVersion] {
        briefs.filter { $0.anchor == anchor }.sorted { $0.version > $1.version }
    }
    public var setAside: Set<CaseMapNodeID> { Set(relevance.filter { $0.isActive && $0.decision == .setAside }.map(\.record)) }
    public var keptIn: Set<CaseMapNodeID> { Set(relevance.filter { $0.isActive && $0.decision == .keep }.map(\.record)) }
    /// BRIEF-06 — a brief written against another state of the case says so (it is never rewritten).
    public func isStale(_ b: CaseBriefVersion) -> Bool { !currentFence.isEmpty && b.fence != currentFence }
}

public nonisolated enum CaseBriefError: Error, Equatable, LocalizedError {
    case emptyBrief
    case versionChanged
    case alreadyAccepted
    case alreadyDecided
    case notFound(String)
    case frozen
    case staleProjection
    case samePerson
    case notAPerson
    public var errorDescription: String? {
        switch self {
        case .emptyBrief: return "Write at least one part of the brief."
        case .versionChanged: return "Someone wrote a newer version of this brief meanwhile. Read it, then write yours as the next version."
        case .alreadyAccepted: return "This version is already accepted. Write a new version to change it."
        case .alreadyDecided: return "There is already a recorded decision for this. Withdraw it first."
        case .notFound(let what): return "The \(what) was not found in this case."
        case .frozen: return "This briefing is frozen: its steps are kept as they were. Make a new briefing to change them."
        case .staleProjection: return "The case changed since the map was read. Choose Refresh, then freeze again — a frozen briefing must record one state."
        case .samePerson: return "Choose two different people."
        case .notAPerson: return "Both must be people of this case."
        }
    }
}

extension CaseFileRepository {

    /// The action kinds a brief writes (left out of the brief's own staleness fence).
    nonisolated static let briefActions = ["briefWritten", "briefAccepted", "briefRelevance", "briefRelevanceWithdrawn", "briefingCreated",
                                           "briefingItemAdded", "briefingItemRemoved", "briefingFrozen", "briefingWithdrawn"]
    /// …and the record kinds their before/after copies are kept under.
    nonisolated static let briefRecordKinds = ["brief", "briefRelevance", "briefing", "briefingItem"]

    // MARK: Identity decisions

    func readIdentityDecisions(caseID: UUID) async throws -> [CasePersonIdentityDecision] {
        try await database.query("""
            SELECT id, case_id, person_a, person_b, decision, rationale, decided_by, decided_at, withdrawn_by, withdrawn_at, withdrawn_reason
            FROM case_person_identity_decisions WHERE case_id = ? ORDER BY decided_at ASC, rowid ASC;
            """, [.uuid(caseID)]).compactMap { r in
            guard let id = r.uuid(0), let c = r.uuid(1), let a = r.uuid(2), let b = r.uuid(3),
                  let d = r.string(4).flatMap(CasePersonIdentityDecision.Decision.init(rawValue:)), let why = r.string(5),
                  let by = r.string(6), let at = r.date(7) else { return nil }
            return CasePersonIdentityDecision(id: id, caseID: c, personA: a, personB: b, decision: d, rationale: why, decidedBy: by, decidedAt: at,
                                              withdrawnBy: r.string(8), withdrawnAt: r.date(9), withdrawnReason: r.string(10))
        }
    }

    /// Record that two case-person rows are, or are not, the same person. Nothing is merged; one active decision per pair.
    @discardableResult
    public func recordIdentityDecision(caseID: UUID, personA: UUID, personB: UUID, decision: CasePersonIdentityDecision.Decision,
                                       rationale: String, actor: String, at date: Date = Date()) async throws -> UUID {
        let why = try Self.clean(rationale, "The reason")
        let who = try Self.clean(actor, "Actor")
        guard personA != personB else { throw CaseBriefError.samePerson }
        let (a, b) = personA.uuidString.lowercased() < personB.uuidString.lowercased() ? (personA, personB) : (personB, personA)
        let id = UUID()
        try await write("cf_idd", caseID: caseID, actor: who, action: "identityDecided", detail: decision.rawValue, at: date,
                        capture: CaseRecordCapture(kind: "identityDecision", table: "case_person_identity_decisions", recordID: id)) { db in
            for p in [a, b] {
                guard try !db.query("SELECT 1 FROM case_people WHERE case_id = ? AND id IN (?, ?) AND removed_at IS NULL;",
                                    [.uuid(caseID), .text(p.uuidString), .text(p.uuidString.lowercased())]).isEmpty else { throw CaseBriefError.notAPerson }
            }
            guard try db.query("SELECT 1 FROM case_person_identity_decisions WHERE case_id = ? AND person_a = ? AND person_b = ? AND withdrawn_at IS NULL;",
                               [.uuid(caseID), .text(a.uuidString.lowercased()), .text(b.uuidString.lowercased())]).isEmpty else { throw CaseBriefError.alreadyDecided }
            try db.exec("""
                INSERT INTO case_person_identity_decisions (id, case_id, person_a, person_b, decision, rationale, decided_by, decided_at)
                VALUES (?,?,?,?,?,?,?,?);
                """, [.uuid(id), .uuid(caseID), .text(a.uuidString.lowercased()), .text(b.uuidString.lowercased()), .text(decision.rawValue),
                      .text(why), .text(who), .date(date)])
        }
        return id
    }

    /// Withdraw an identity decision with the reason: the pair is pending again; both rows were never changed.
    public func withdrawIdentityDecision(caseID: UUID, id: UUID, reason: String, actor: String, at date: Date = Date()) async throws {
        let why = try Self.clean(reason, "The reason")
        let who = try Self.clean(actor, "Actor")
        try await write("cf_iddw", caseID: caseID, actor: who, action: "identityDecisionWithdrawn", detail: why, at: date,
                        capture: CaseRecordCapture(kind: "identityDecision", table: "case_person_identity_decisions", recordID: id)) { db in
            guard let r = try db.query("SELECT withdrawn_at FROM case_person_identity_decisions WHERE id = ? AND case_id = ?;", [.uuid(id), .uuid(caseID)]).first else {
                throw CaseBriefError.notFound("decision")
            }
            guard r.isNull(0) else { throw CaseContractError.alreadyWithdrawn }
            try db.exec("UPDATE case_person_identity_decisions SET withdrawn_by = ?, withdrawn_at = ?, withdrawn_reason = ? WHERE id = ?;",
                        [.text(who), .date(date), .text(why), .uuid(id)])
        }
    }

    // MARK: Read

    public func briefLedger(caseID: UUID) async throws -> CaseBriefLedger {
        var out = CaseBriefLedger()
        out.briefs = try await database.query("""
            SELECT id, case_id, anchor_kind, anchor_id, version, purpose, position, unresolved, alternatives, next_work, origin, generated_by, fence,
                   written_by, written_at, accepted_by, accepted_at, supersedes_id
            FROM case_briefs WHERE case_id = ? ORDER BY anchor_kind, anchor_id, version;
            """, [.uuid(caseID)]).compactMap { r in
            guard let id = r.uuid(0), let c = r.uuid(1), let k = r.string(2).flatMap(CaseMapRecordKind.init(rawValue:)), let aid = r.string(3),
                  let v = r.int(4), let origin = r.string(10).flatMap(CaseBriefVersion.Origin.init(rawValue:)), let fence = r.string(12),
                  let by = r.string(13), let at = r.date(14) else { return nil }
            return CaseBriefVersion(id: id, caseID: c, anchor: CaseMapNodeID(caseID: c, kind: k, recordID: aid), version: Int(v),
                                    purpose: r.string(5), position: r.string(6), unresolved: r.string(7), alternatives: r.string(8), nextWork: r.string(9),
                                    origin: origin, generatedBy: r.string(11), fence: fence, writtenBy: by, writtenAt: at,
                                    acceptedBy: r.string(15), acceptedAt: r.date(16), supersedesID: r.uuid(17))
        }
        out.relevance = try await database.query("""
            SELECT id, case_id, record_kind, record_id, decision, reason, decided_by, decided_at, withdrawn_at
            FROM case_brief_relevance WHERE case_id = ? ORDER BY decided_at, rowid;
            """, [.uuid(caseID)]).compactMap { r in
            guard let id = r.uuid(0), let c = r.uuid(1), let k = r.string(2).flatMap(CaseMapRecordKind.init(rawValue:)), let rid = r.string(3),
                  let d = r.string(4).flatMap(CaseBriefRelevance.Decision.init(rawValue:)), let why = r.string(5), let by = r.string(6), let at = r.date(7) else { return nil }
            return CaseBriefRelevance(id: id, caseID: c, record: CaseMapNodeID(caseID: c, kind: k, recordID: rid), decision: d, reason: why,
                                      decidedBy: by, decidedAt: at, withdrawnAt: r.date(8))
        }
        let items = try await database.query("""
            SELECT id, briefing_id, ordinal, item_kind, record_kind, record_id, view_id, note, revision_at_add, added_by, added_at, removed_at
            FROM case_briefing_items WHERE case_id = ? ORDER BY briefing_id, ordinal, added_at;
            """, [.uuid(caseID)]).compactMap { r -> CaseBriefingItem? in
            guard let id = r.uuid(0), let b = r.uuid(1), let o = r.int(2), let k = r.string(3).flatMap(CaseBriefingItem.Kind.init(rawValue:)),
                  let by = r.string(9), let at = r.date(10) else { return nil }
            let record = r.string(4).flatMap(CaseMapRecordKind.init(rawValue:)).flatMap { kind in r.string(5).map { CaseMapNodeID(caseID: caseID, kind: kind, recordID: $0) } }
            return CaseBriefingItem(id: id, briefingID: b, ordinal: Int(o), kind: k, record: record, viewID: r.uuid(6), note: r.string(7),
                                    revisionAtAdd: r.string(8), addedBy: by, addedAt: at, removedAt: r.date(11))
        }
        let byBriefing = Dictionary(grouping: items, by: \.briefingID)
        out.briefings = try await database.query("""
            SELECT id, case_id, title, purpose, created_by, created_at, frozen_by, frozen_at, frozen_fence, frozen_json, withdrawn_at, withdrawn_reason
            FROM case_briefings WHERE case_id = ? ORDER BY created_at, rowid;
            """, [.uuid(caseID)]).compactMap { r in
            guard let id = r.uuid(0), let c = r.uuid(1), let title = r.string(2), let by = r.string(4), let at = r.date(5) else { return nil }
            var frozen: [CaseBriefingFrozenItem]?
            var problem: String?
            if let raw = r.string(9) {
                do { frozen = try JSONDecoder().decode([CaseBriefingFrozenItem].self, from: Data(raw.utf8)) } catch {
                    KalsmritikoshLog.app.error("Briefing \(id.uuidString, privacy: .public): frozen state unreadable: \(error.localizedDescription, privacy: .public)")
                    problem = "The recorded state of this frozen briefing could not be read (\(error.localizedDescription)). It is not shown as empty; its steps are listed by reference."
                }
            }
            return CaseBriefing(id: id, caseID: c, title: title, purpose: r.string(3), createdBy: by, createdAt: at, frozenBy: r.string(6),
                                frozenAt: r.date(7), frozenFence: r.string(8), frozen: frozen, frozenProblem: problem,
                                withdrawnAt: r.date(10), withdrawnReason: r.string(11), items: byBriefing[id] ?? [])
        }
        out.currentFence = try await database.withSavepoint("cfbrief_\(UUID().uuidString.prefix(8))") { db in
            try CaseMapRepository.fence(db, caseID: caseID, ignoringActions: Self.briefActions, ignoringRevisionKinds: Self.briefRecordKinds)
        }
        return out
    }

    // MARK: Briefs (BRIEF-02 / BRIEF-06)

    /// Write the next version of a brief (a draft). `expectedVersion` is the newest version the person was looking at
    /// (0: none); a newer one written meanwhile refuses the write instead of silently replacing it.
    @discardableResult
    public func writeBrief(caseID: UUID, anchor: CaseMapNodeID, text: CaseBriefText, expectedVersion: Int, actor: String,
                           at date: Date = Date()) async throws -> UUID {
        let who = try Self.clean(actor, "Actor")
        guard !text.isEmpty else { throw CaseBriefError.emptyBrief }
        guard anchor.caseID == caseID else { throw CaseWorkError.notInCase("item") }
        let id = UUID()
        func clean(_ s: String?) -> SQLValue { Self.blankToNil(s).map { .text($0) } ?? .null }
        try await write("cf_brief", caseID: caseID, actor: who, action: "briefWritten", detail: "\(anchor.key) v\(expectedVersion + 1)", at: date,
                        capture: CaseRecordCapture(kind: "brief", table: "case_briefs", recordID: id)) { db in
            if anchor.kind != .caseFile || anchor.recordID != caseID.uuidString.lowercased() {
                guard CaseMapRecordKind.linkable.contains(anchor.kind), try CaseMapRepository.belongs(db, anchor, caseID: caseID) else {
                    throw CaseWorkError.notInCase(anchor.kind.rawValue)
                }
            }
            let newest = Int(try db.query("SELECT coalesce(MAX(version), 0) FROM case_briefs WHERE case_id = ? AND anchor_kind = ? AND anchor_id = ?;",
                                          [.uuid(caseID), .text(anchor.kind.rawValue), .text(anchor.recordID)]).first?.int(0) ?? 0)
            guard newest == expectedVersion else { throw CaseBriefError.versionChanged }
            let previous = try db.query("SELECT id FROM case_briefs WHERE case_id = ? AND anchor_kind = ? AND anchor_id = ? AND version = ?;",
                                        [.uuid(caseID), .text(anchor.kind.rawValue), .text(anchor.recordID), .integer(Int64(newest))]).first?.string(0)
            let fence = try CaseMapRepository.fence(db, caseID: caseID, ignoringActions: Self.briefActions, ignoringRevisionKinds: Self.briefRecordKinds)
            try db.exec("""
                INSERT INTO case_briefs (id, case_id, anchor_kind, anchor_id, version, purpose, position, unresolved, alternatives, next_work, origin,
                                         fence, written_by, written_at, supersedes_id)
                VALUES (?,?,?,?,?,?,?,?,?,?, 'manual', ?,?,?,?);
                """, [.uuid(id), .uuid(caseID), .text(anchor.kind.rawValue), .text(anchor.recordID), .integer(Int64(newest + 1)),
                      clean(text.purpose), clean(text.position), clean(text.unresolved), clean(text.alternatives), clean(text.nextWork),
                      .text(fence), .text(who), .date(date), previous.map { .text($0) } ?? .null])
        }
        return id
    }

    /// Accept a draft version. Once accepted it is never edited (the database refuses it); a change is a new version.
    public func acceptBrief(caseID: UUID, id: UUID, actor: String, at date: Date = Date()) async throws {
        let who = try Self.clean(actor, "Actor")
        try await write("cf_briefa", caseID: caseID, actor: who, action: "briefAccepted", detail: nil, at: date,
                        capture: CaseRecordCapture(kind: "brief", table: "case_briefs", recordID: id)) { db in
            guard let r = try db.query("SELECT accepted_at FROM case_briefs WHERE id = ? AND case_id = ?;", [.uuid(id), .uuid(caseID)]).first else {
                throw CaseBriefError.notFound("brief")
            }
            guard r.isNull(0) else { throw CaseBriefError.alreadyAccepted }
            try db.exec("UPDATE case_briefs SET accepted_by = ?, accepted_at = ? WHERE id = ?;", [.text(who), .date(date), .uuid(id)])
        }
    }

