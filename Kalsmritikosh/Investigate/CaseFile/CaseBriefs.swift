//  SM-01, SM-10; schema v179). Orientation without a model:
//
//  • CaseMapBrief — the case or branch brief, COMPUTED from the projection the map shows: purpose, scope, the current
//    recorded position, what is unresolved, contrary material and open alternatives beside the position, material
//    changes and next work. Every factual entry names the canonical record it comes from (so it opens into the map) and
//    says why it appears. Nothing is ranked by relevance: each section lists every item it holds, in a stable order, and
//    says how many. Evidential states and work states are separate lists; there is no percentage anywhere.
//  • Investigator briefs (case_briefs) — the person's own structured brief, in numbered versions. A version is accepted
//    once and never edited; new material never rewrites it — the brief says it was written before later changes.
//  • Relevance (case_brief_relevance) — "set aside from the brief" with a reason; the record and its evidence are
//    untouched, and the brief lists what was set aside.
//  • Briefings (case_briefings + items) — a curated path for a handover or review: records, branches (frames), saved
//    views and notes, by reference. A live briefing shows what changed since each step was added; a frozen one keeps
//    the state of every step at the moment it was frozen. Both open into the full map.
//  • CaseReturnView (BRIEF-07) — what a returning investigator needs: where they were, what changed for THEM (unseen),
//    what needs a review (substantive), work due and blocked work.
//  • Identity decisions (GRAPH-09) — "the same person" / "different people" about two case-person rows, recorded and
//    withdrawable; nothing is merged, so undoing a wrong decision leaves both rows' histories exactly as they were.
//
//  Every write goes through CaseFileRepository's one savepoint with its case_actions row and a before/after copy. Nothing
//  here calls a model or the network.
//

