// MARK: - Identity decisions (GRAPH-09)

public nonisolated struct CasePersonIdentityDecision: Identifiable, Sendable, Equatable, Hashable {
    public enum Decision: String, Sendable, CaseIterable { case samePerson, differentPeople
        public var label: String { self == .samePerson ? "The same person" : "Different people" }
    }
    public let id: UUID
    public let caseID: UUID
    /// The pair, lower-case ids, `personA < personB`.
    public let personA: UUID
    public let personB: UUID
    public let decision: Decision
    public let rationale: String
    public let decidedBy: String
    public let decidedAt: Date
    public let withdrawnBy: String?
    public let withdrawnAt: Date?
    public let withdrawnReason: String?
    public var isActive: Bool { withdrawnAt == nil }
    public var pairKey: String { Self.pairKey(personA, personB) }
    public static func pairKey(_ a: UUID, _ b: UUID) -> String {
        let x = a.uuidString.lowercased(), y = b.uuidString.lowercased()
        return x < y ? "\(x)|\(y)" : "\(y)|\(x)"
    }
}

// MARK: - Investigator briefs, relevance and briefings (v179)

/// One version of the investigator's structured brief of the case or of one branch.
public nonisolated struct CaseBriefVersion: Identifiable, Sendable, Equatable {
    public enum Origin: String, Sendable { case manual, generated }
    public let id: UUID
    public let caseID: UUID
    /// The record the brief is about (the case itself for the case brief).
    public let anchor: CaseMapNodeID
    public let version: Int
    public let purpose: String?
    public let position: String?
    public let unresolved: String?
    public let alternatives: String?
    public let nextWork: String?
    public let origin: Origin
    /// For generated text: what generated it (it is labelled as generated wherever it is shown). Nil for a person's text.
    public let generatedBy: String?
    /// The case revision fence it was written against.
    public let fence: String
    public let writtenBy: String
    public let writtenAt: Date
    public let acceptedBy: String?
    public let acceptedAt: Date?
    public let supersedesID: UUID?
    public var isAccepted: Bool { acceptedAt != nil }
    /// "Written by Ada" / "Generated by …, not reviewed" — never passes as a person's reviewed text.
    public var attribution: String {
        switch origin {
        case .manual: return "Written by \(writtenBy)" + (acceptedBy.map { ", accepted by \($0)" } ?? " — draft, not accepted")
        case .generated: return "Generated text (\(generatedBy ?? "not recorded")) — " + (acceptedBy.map { "accepted by \($0)" } ?? "not reviewed by a person")
        }
    }
}

/// What the person writes in a brief (every field optional; at least one is required).
public nonisolated struct CaseBriefText: Sendable, Equatable {
    public var purpose: String?
    public var position: String?
    public var unresolved: String?
    public var alternatives: String?
    public var nextWork: String?
    public init(purpose: String? = nil, position: String? = nil, unresolved: String? = nil, alternatives: String? = nil, nextWork: String? = nil) {
        self.purpose = purpose; self.position = position; self.unresolved = unresolved; self.alternatives = alternatives; self.nextWork = nextWork
    }
    var isEmpty: Bool { [purpose, position, unresolved, alternatives, nextWork].allSatisfy { ($0 ?? "").trimmingCharacters(in: .whitespacesAndNewlines).isEmpty } }
}

