    // MARK: Briefings (BRIEF-08)

    @discardableResult
    public func createBriefing(caseID: UUID, title: String, purpose: String?, actor: String, at date: Date = Date()) async throws -> UUID {
        let name = try Self.clean(title, "The title")
        let who = try Self.clean(actor, "Actor")
        let id = UUID()
        try await write("cf_bfg", caseID: caseID, actor: who, action: "briefingCreated", detail: name, at: date,
                        capture: CaseRecordCapture(kind: "briefing", table: "case_briefings", recordID: id)) { db in
            try db.exec("INSERT INTO case_briefings (id, case_id, title, purpose, created_by, created_at) VALUES (?,?,?,?,?,?);",
                        [.uuid(id), .uuid(caseID), .text(name), .optionalText(Self.blankToNil(purpose)), .text(who), .date(date)])
        }
        return id
    }

    /// Add a step: a record or a frame (with the record's revision now, from the map), a saved view of this case, or a note.
    @discardableResult
    public func addBriefingItem(caseID: UUID, briefingID: UUID, kind: CaseBriefingItem.Kind, record: CaseMapNodeID? = nil, revision: String? = nil,
                                viewID: UUID? = nil, note: String? = nil, actor: String, at date: Date = Date()) async throws -> UUID {
        let who = try Self.clean(actor, "Actor")
        switch kind {
        case .record, .frame: guard let r = record, r.caseID == caseID else { throw CaseWorkError.notInCase("item") }
        case .savedView: guard viewID != nil else { throw CaseBriefError.notFound("saved view") }
        case .note: guard Self.blankToNil(note) != nil else { throw CaseFileError.blank("The note") }
        }
        let id = UUID()
        try await write("cf_bfi", caseID: caseID, actor: who, action: "briefingItemAdded", detail: "\(kind.rawValue) \(record?.key ?? viewID?.uuidString ?? "note")",
                        at: date, capture: CaseRecordCapture(kind: "briefingItem", table: "case_briefing_items", recordID: id)) { db in
            guard let b = try db.query("SELECT frozen_at, withdrawn_at FROM case_briefings WHERE id = ? AND case_id = ?;", [.uuid(briefingID), .uuid(caseID)]).first else {
                throw CaseBriefError.notFound("briefing")
            }
            guard b.isNull(0) else { throw CaseBriefError.frozen }
            guard b.isNull(1) else { throw CaseContractError.alreadyWithdrawn }
            if let r = record {
                let isCase = r.kind == .caseFile && r.recordID == caseID.uuidString.lowercased()
                // A record that is not linkable (a contradiction, a money movement) is still a case record of the map; only
                // linkable records can be checked inside the write, the rest are checked against the map when shown.
                if !isCase, CaseMapRecordKind.linkable.contains(r.kind), try !CaseMapRepository.belongs(db, r, caseID: caseID) {
                    throw CaseWorkError.notInCase(r.kind.rawValue)
                }
            }
            if let v = viewID {
                guard try !db.query("SELECT 1 FROM case_map_views WHERE id = ? AND case_id = ?;", [.uuid(v), .uuid(caseID)]).isEmpty else {
                    throw CaseBriefError.notFound("saved view")
                }
            }
            let next = Int(try db.query("SELECT coalesce(MAX(ordinal), -1) + 1 FROM case_briefing_items WHERE briefing_id = ?;", [.uuid(briefingID)]).first?.int(0) ?? 0)
            try db.exec("""
                INSERT INTO case_briefing_items (id, case_id, briefing_id, ordinal, item_kind, record_kind, record_id, view_id, note, revision_at_add, added_by, added_at)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?);
                """, [.uuid(id), .uuid(caseID), .uuid(briefingID), .integer(Int64(next)), .text(kind.rawValue),
                      record.map { .text($0.kind.rawValue) } ?? .null, record.map { .text($0.recordID) } ?? .null,
                      viewID.map { .uuid($0) } ?? .null, .optionalText(Self.blankToNil(note)), .optionalText(revision), .text(who), .date(date)])
        }
        return id
    }

    public func removeBriefingItem(caseID: UUID, itemID: UUID, actor: String, at date: Date = Date()) async throws {
        let who = try Self.clean(actor, "Actor")
        try await write("cf_bfir", caseID: caseID, actor: who, action: "briefingItemRemoved", detail: nil, at: date,
                        capture: CaseRecordCapture(kind: "briefingItem", table: "case_briefing_items", recordID: itemID)) { db in
            guard let r = try db.query("""
                SELECT i.removed_at, b.frozen_at FROM case_briefing_items i JOIN case_briefings b ON b.id = i.briefing_id WHERE i.id = ? AND i.case_id = ?;
                """, [.uuid(itemID), .uuid(caseID)]).first else { throw CaseBriefError.notFound("step") }
            guard r.isNull(1) else { throw CaseBriefError.frozen }
            guard r.isNull(0) else { throw CaseContractError.alreadyWithdrawn }
            try db.exec("UPDATE case_briefing_items SET removed_by = ?, removed_at = ? WHERE id = ?;", [.text(who), .date(date), .uuid(itemID)])
        }
    }

    /// Freeze a briefing: the state of every step, from the map read under `fence`, is recorded with it. Refused when the
    /// case changed since that read (a frozen briefing records ONE state), when it is already frozen, or withdrawn.
    public func freezeBriefing(caseID: UUID, briefingID: UUID, projection: CaseMapProjection, fence: String?, actor: String,
                               at date: Date = Date()) async throws {
        let who = try Self.clean(actor, "Actor")
        guard projection.caseID == caseID, let fence else { throw CaseBriefError.staleProjection }
        let ledger = try await briefLedger(caseID: caseID)
        guard let briefing = ledger.briefings.first(where: { $0.id == briefingID }) else { throw CaseBriefError.notFound("briefing") }
        guard !briefing.isFrozen else { throw CaseBriefError.frozen }
        let frozen = CaseBriefings.freeze(briefing, in: projection)
        let json = String(decoding: try JSONEncoder().encode(frozen), as: UTF8.self)
        try await write("cf_bff", caseID: caseID, actor: who, action: "briefingFrozen", detail: briefing.title, at: date,
                        capture: CaseRecordCapture(kind: "briefing", table: "case_briefings", recordID: briefingID)) { db in
            // The validated revision fence (as for a recorded state): the map the steps were read from is the case now.
            guard try CaseMapRepository.fence(db, caseID: caseID) == fence else { throw CaseBriefError.staleProjection }
            guard let r = try db.query("SELECT frozen_at, withdrawn_at FROM case_briefings WHERE id = ? AND case_id = ?;", [.uuid(briefingID), .uuid(caseID)]).first else {
                throw CaseBriefError.notFound("briefing")
            }
            guard r.isNull(0) else { throw CaseBriefError.frozen }
            guard r.isNull(1) else { throw CaseContractError.alreadyWithdrawn }
            try db.exec("UPDATE case_briefings SET frozen_by = ?, frozen_at = ?, frozen_fence = ?, frozen_json = ? WHERE id = ?;",
                        [.text(who), .date(date), .text(fence), .text(json), .uuid(briefingID)])
        }
    }

    public func withdrawBriefing(caseID: UUID, briefingID: UUID, reason: String, actor: String, at date: Date = Date()) async throws {
        let why = try Self.clean(reason, "The reason")
        let who = try Self.clean(actor, "Actor")
        try await write("cf_bfw", caseID: caseID, actor: who, action: "briefingWithdrawn", detail: why, at: date,
                        capture: CaseRecordCapture(kind: "briefing", table: "case_briefings", recordID: briefingID)) { db in
            guard let r = try db.query("SELECT withdrawn_at FROM case_briefings WHERE id = ? AND case_id = ?;", [.uuid(briefingID), .uuid(caseID)]).first else {
                throw CaseBriefError.notFound("briefing")
            }
            guard r.isNull(0) else { throw CaseContractError.alreadyWithdrawn }
            try db.exec("UPDATE case_briefings SET withdrawn_by = ?, withdrawn_at = ?, withdrawn_reason = ? WHERE id = ?;",
                        [.text(who), .date(date), .text(why), .uuid(briefingID)])
        }
    }
}

// MARK: - Briefing steps resolved (live) or recorded (frozen)

public nonisolated enum CaseBriefings {
    /// One step as shown: its title and state now (live) or as recorded (frozen), and what changed.
    public struct Step: Identifiable, Sendable, Equatable {
        public let id: UUID
        public let kind: CaseBriefingItem.Kind
        public let record: CaseMapNodeID?
        public let viewID: UUID?
        public let title: String
        public let state: String
        /// Live: what changed since the step was added (nil: unchanged). Frozen: nil (the recorded state is shown).
        public let change: String?
        /// The record is not in the case's map now (live) or was not when frozen.
        public let missing: Bool
    }

    static func describe(_ n: CaseMapNode) -> (title: String, state: String) {
        (n.title, n.status.kind.label + ": " + n.status.text + (n.review == .notApplicable ? "" : " · " + n.review.label))
    }

    /// The recorded state of every active step (a record or frame by its node now; a view or a note as it is).
    public static func freeze(_ b: CaseBriefing, in p: CaseMapProjection) -> [CaseBriefingFrozenItem] {
        b.activeItems.map { i in
            let n = i.record.flatMap { p.node($0) }
            let d = n.map(describe)
            return CaseBriefingFrozenItem(itemID: i.id, kind: i.kind.rawValue, recordKind: i.record?.kind.rawValue, recordID: i.record?.recordID,
                                          viewID: i.viewID, title: d?.title ?? (i.kind == .note ? "Note" : i.kind == .savedView ? "Saved view" : "Item not in the case"),
                                          state: d?.state ?? "", review: n?.review.rawValue ?? CaseMapReviewState.notApplicable.rawValue,
                                          revision: n?.revision, wording: n?.wording.map { String($0.prefix(2_000)) }, note: i.note,
                                          missing: i.record != nil && n == nil)
        }
    }

    /// The steps of a briefing: a frozen one as recorded; a live one resolved against the case now, saying what changed.
    public static func steps(_ b: CaseBriefing, in p: CaseMapProjection?, viewName: (UUID) -> String?) -> [Step] {
        if b.isFrozen, let frozen = b.frozen {
            return frozen.map { f in
                let record = f.recordKind.flatMap(CaseMapRecordKind.init(rawValue:)).flatMap { k in f.recordID.map { CaseMapNodeID(caseID: b.caseID, kind: k, recordID: $0) } }
                return Step(id: f.itemID, kind: CaseBriefingItem.Kind(rawValue: f.kind) ?? .note, record: record, viewID: f.viewID,
                            title: f.kind == "note" ? (f.note ?? "Note") : f.title, state: f.state, change: nil, missing: f.missing)
            }
        }
        return b.activeItems.map { i in
            switch i.kind {
            case .note:
                return Step(id: i.id, kind: .note, record: nil, viewID: nil, title: i.note ?? "Note", state: "", change: nil, missing: false)
            case .savedView:
                let name = i.viewID.flatMap(viewName)
                return Step(id: i.id, kind: .savedView, record: nil, viewID: i.viewID, title: name ?? "A saved view that was removed",
                            state: name == nil ? "This saved view is no longer in the case" : "Saved view", change: nil, missing: name == nil)
            case .record, .frame:
                guard let r = i.record, let n = p?.node(r) else {
                    return Step(id: i.id, kind: i.kind, record: i.record, viewID: nil, title: "Item not in the case's map now",
                                state: "It was removed, erased or left the case scope after it was added.", change: "No longer in the case", missing: true)
                }
                let d = describe(n)
                let changed = (i.revisionAtAdd ?? "") != (n.revision ?? "")
                return Step(id: i.id, kind: i.kind, record: r, viewID: nil, title: d.title, state: d.state,
                            change: changed ? "Changed since it was added on \(i.addedAt.formatted(date: .abbreviated, time: .omitted))" : (n.status.kind == .stale ? "Needs review — a source changed" : nil),
                            missing: false)
            }
        }
    }
}

// MARK: - The computed brief (BRIEF-01, BRIEF-03, BRIEF-04, BRIEF-05)

public nonisolated struct CaseMapBrief: Sendable, Equatable {
    /// One factual entry: the record it opens, what it says, and why it appears here.
    public struct Entry: Identifiable, Sendable, Equatable, Hashable {
        public let node: CaseMapNodeID
        public let text: String
        /// Why it is in this section, in words (BRIEF-05).
        public let why: String
        /// Its basis: the record's state and how many sources it cites.
        public let basis: String
        public var id: String { node.key + "|" + why }
    }
    public struct Section: Sendable, Equatable, Identifiable {
        public let id: String
        public let title: String
        /// Every entry the section holds (never cut by ranking); the view pages them.
        public let entries: [Entry]
        /// What the section says when it holds nothing (an absence is stated, not left blank).
        public let empty: String
    }
    /// The record the brief is about (the case itself, or a branch anchor).
    public let anchor: CaseMapNodeID
    public let purpose: String?
    /// What the brief covers and what it could not: the records reached, parts not read, branch limits.
    public let scope: [String]
    public let sections: [Section]
    /// BRIEF-03 — evidential states, each a separate count (no percentage), and work states, separately.
    public let evidentialStates: [(label: String, count: Int)]
    public let workStates: [(label: String, count: Int)]
    /// Items the person set aside from the brief (they stay in the case; listed here so nothing disappears silently).
    public let setAside: [Entry]

    public static func == (a: CaseMapBrief, b: CaseMapBrief) -> Bool {
        a.anchor == b.anchor && a.purpose == b.purpose && a.scope == b.scope && a.sections == b.sections && a.setAside == b.setAside
            && a.evidentialStates.map(\.label) == b.evidentialStates.map(\.label) && a.evidentialStates.map(\.count) == b.evidentialStates.map(\.count)
            && a.workStates.map(\.label) == b.workStates.map(\.label) && a.workStates.map(\.count) == b.workStates.map(\.count)
    }
    public func section(_ id: String) -> Section? { sections.first { $0.id == id } }
    /// Every record the brief names (each entry opens into the map).
    public var allEntries: [Entry] { sections.flatMap(\.entries) }

    /// The brief of the case (anchor nil) or of the branch reached from `anchor` (through typed relationships, cycle-safe,
    /// within `budget` records — what the budget did not reach is stated in the scope).
    public static func compute(_ p: CaseMapProjection, anchor: CaseMapNodeID? = nil, changed: Set<CaseMapNodeID> = [],
                               setAside: Set<CaseMapNodeID> = [], budget: Int = 5_000, now: Date = Date()) -> CaseMapBrief {
        let caseNode = CaseMapNodeID(caseID: p.caseID, kind: .caseFile, id: p.caseID)
        let root = anchor ?? caseNode
        var scope: [String] = []
        let members: [CaseMapNode]
        if let anchor, anchor != caseNode {
            let t = CaseMapFrames.traverse(from: anchor, in: p, budget: budget)
            members = t.depth.keys.sorted().compactMap { p.node($0) }
            scope.append("This branch: \(members.count) record(s) reached from “\(p.node(anchor)?.title ?? anchor.key)” through their recorded relationships.")
            if !t.exhausted { scope.append("\(t.continuation.count) further record(s) were reached but not expanded within the brief's limit of \(budget); open the branch to go further.") }
        } else {
            members = p.nodes
            scope.append("The whole case as the map holds it: \(p.nodes.count) record(s).")
        }
        if !p.failedParts.isEmpty { scope.append("Not read, so not in this brief: " + p.failedParts.map(\.label).joined(separator: ", ") + ".") }
        scope.append("Built from the case's records on this Mac; no AI was used. It ranks nothing: every item of each section is listed.")
        let inBranch = Set(members.map(\.id))
        let hidden = setAside
        func sources(_ n: CaseMapNode) -> String { n.sources.isEmpty ? "no cited source" : "\(n.sources.count) cited source(s)" }
        func entry(_ n: CaseMapNode, _ why: String) -> Entry {
            // S4 (REPORT-03): a qualified point is never summarised without its qualifications.
            Entry(node: n.id, text: n.qualifications.isEmpty ? n.title : n.title + " — QUALIFIED: " + n.qualifications.joined(separator: "; "),
                  why: why, basis: "\(n.status.kind.label): \(n.status.text) · \(sources(n))")
        }
        let shown = members.filter { !hidden.contains($0.id) }
        func linksIn(_ n: CaseMapNode, _ type: CaseMapLinkType) -> [CaseMapLink] { p.links(of: n.id).filter { $0.to == n.id && $0.type == type && inBranch.contains($0.from) } }

        // The current recorded position: what has been decided or accepted (as recorded — not that it is true).
        var position: [Entry] = []
        var unresolved: [Entry] = []
        for n in shown {
            switch n.id.kind {
            case .allegation:
                if n.review == .confirmed { position.append(entry(n, "A question with a recorded decision")) }
                else { unresolved.append(entry(n, "An open question — no decision recorded")) }
            case .hypothesis:
                if n.review == .confirmed { position.append(entry(n, "A hypothesis recorded as confirmed")) }
                else if n.review == .unreviewed { unresolved.append(entry(n, "A hypothesis or lead not yet decided")) }
            case .contradiction:
                if n.review == .confirmed { position.append(entry(n, "A contradiction confirmed on review — both accounts are kept")) }
                else if n.review.awaitingReview { unresolved.append(entry(n, n.review == .reopened ? "A contradiction reopened because a source changed" : "A possible contradiction waiting for a decision")) }
            case .reportPoint:
                if n.review == .accepted { position.append(entry(n, "A report point accepted on review (what the report says, not that it is true)")) }
                else if n.review == .unreviewed { unresolved.append(entry(n, "A report point not yet reviewed")) }
            case .reportItem:
                if n.status.text.hasPrefix("Excluded") == false { position.append(entry(n, "Selected for the case report")) }
            case .moneyTransaction:
                if n.review == .unreviewed { unresolved.append(entry(n, "A money movement whose identity needs checking")) }
            default:
                break
            }
        }
        // BRIEF-04 — contrary material and open alternatives, beside the position (all of them; none ranked away).
        var alternatives: [Entry] = []
        var seenAlt = Set<CaseMapNodeID>()
        for n in shown where n.kind == .question || n.kind == .hypothesis {
            for l in linksIn(n, .challenges) {
                guard let c = p.node(l.from), !hidden.contains(c.id), seenAlt.insert(c.id).inserted else { continue }
                alternatives.append(Entry(node: c.id, text: c.title, why: "Challenges “\(n.title)”", basis: "\(l.status.text) · \(l.assertedBy.label)"))
            }
        }
        for n in shown where n.id.kind == .hypothesis && n.review != .rejected && seenAlt.insert(n.id).inserted {
            alternatives.append(entry(n, n.review == .confirmed ? "A recorded hypothesis — alternatives to it are listed with it" : "An alternative explanation still open"))
        }
        for n in shown where n.id.kind == .contradiction && n.review != .dismissed && seenAlt.insert(n.id).inserted {
            alternatives.append(entry(n, "Two accounts that differ — both are kept"))
        }
        // Material changes: what changed since the person's seen position, what rests on a changed source, what was reopened.
        var changes: [Entry] = []
        for n in shown {
            if changed.contains(n.id) { changes.append(entry(n, "Changed since you last marked the changes as seen")) }
            else if n.status.kind == .stale || n.review == .reopened || n.changedSourceWarning != nil {
                changes.append(entry(n, n.changedSourceWarning ?? "Needs review — a source changed since it was decided or carried"))
            }
        }
        // Next work: open actions and requests — overdue first, then by due date, then by title (deadlines, not relevance).
        let work = shown.filter { $0.workOpen == true }.sorted { a, b in
            let ao = a.status.text.hasSuffix("overdue"), bo = b.status.text.hasSuffix("overdue")
            if ao != bo { return ao }
            switch (a.eventDate, b.eventDate) {
            case let (x?, y?) where x != y: return x < y
            case (_?, nil): return true
            case (nil, _?): return false
            default: return a.title != b.title ? a.title < b.title : a.id < b.id
            }
        }
        let next = work.map { n in
            entry(n, n.workBlocked ? "Open work, marked blocked" : n.status.text.hasSuffix("overdue") ? "Open work, overdue"
                  : n.eventDate.map { "Open work, due \($0.formatted(date: .abbreviated, time: .omitted))" } ?? "Open work, no due date")
        }

        // BRIEF-03 — evidential states (of the material) and work states (of the tasks), never one progress figure.
        let questions = shown.filter { $0.kind == .question && $0.id.kind != .caseFile }
        let supported = questions.filter { !linksIn($0, .supports).isEmpty }.count
        let challenged = questions.filter { !linksIn($0, .challenges).isEmpty }.count
        let material = shown.filter { [.statement, .event, .evidence, .money].contains($0.kind) }
        let evidential: [(String, Int)] = [
            ("Reported — points and statements recorded, not yet reviewed", shown.filter { $0.kind == .statement && $0.review == .unreviewed }.count),
            ("Questions with supporting material recorded", supported),
            ("Questions with challenging material recorded", challenged),
            ("Material not yet assessed", material.filter { $0.status.kind == .unassessed || $0.status.kind == .unsupported }.count),
            ("Reviewed (accepted, rejected, confirmed or dismissed)", shown.filter { [.accepted, .rejected, .confirmed, .dismissed].contains($0.review) }.count),
            ("Questions concluded with a recorded decision", questions.filter { $0.review == .confirmed }.count),
        ]
        let tasks = shown.filter { $0.workOpen != nil }
        let workStates: [(String, Int)] = [
            ("Open work", tasks.filter { $0.workOpen == true && !$0.workBlocked }.count),
            ("Blocked work", tasks.filter { $0.workBlocked }.count),
            ("Finished work (finishing work does not answer its question)", tasks.filter { $0.workOpen == false }.count),
        ]
        let rootNode = p.node(root)
        let purpose: String? = root == caseNode ? p.question : (rootNode?.wording ?? rootNode?.title)
        return CaseMapBrief(anchor: root, purpose: purpose, scope: scope, sections: [
            Section(id: "position", title: "Current recorded position", entries: position,
                    empty: "Nothing has been decided or accepted yet. That is not a finding that nothing happened."),
            Section(id: "unresolved", title: "Unresolved", entries: unresolved, empty: "Nothing recorded as unresolved."),
            Section(id: "alternatives", title: "Contrary material and alternatives", entries: alternatives,
                    empty: "No challenging material, open hypothesis or differing account is recorded. Absence of contrary material in the case is not proof there is none."),
            Section(id: "changes", title: "Material changes", entries: changes, empty: "Nothing changed since you marked the changes as seen, and nothing rests on a changed source."),
            Section(id: "next", title: "Next work", entries: next, empty: "No open action or request is recorded."),
        ], evidentialStates: evidential.map { (label: $0.0, count: $0.1) }, workStates: workStates.map { (label: $0.0, count: $0.1) },
           setAside: members.filter { hidden.contains($0.id) }.map { entry($0, "Set aside from the brief by you — still in the case") })
    }
}

// MARK: - The personal return view (BRIEF-07)

public nonisolated struct CaseReturnView: Sendable, Equatable {
    /// Where the person was: the open frames and the selected record (nil: nothing to resume).
    public let resumeFrames: [CaseMapNodeID]
    public let resumeSelection: CaseMapNodeID?
    /// PERSONAL: changes the person has not marked as seen (seeing is not reviewing).
    public let unseen: [CaseMapBrief.Entry]
    /// SUBSTANTIVE: items waiting for a review decision, whoever saw them.
    public let reviewRequired: [CaseMapBrief.Entry]
    public let due: [CaseMapBrief.Entry]
    public let blocked: [CaseMapBrief.Entry]
    /// A failed feed read is said, never shown as "nothing changed".
    public let feedProblem: String?

    public static func compute(_ p: CaseMapProjection, feed: CaseChangeFeedLoad?, memory: CaseMapWorkspaceMemory?, now: Date = Date(),
                               dueWithin days: Int = 7) -> CaseReturnView {
        var unseen: [CaseMapBrief.Entry] = []
        var problem: String?
        switch feed?.state {
        case .failed(let why)?: problem = "What changed could not be read: \(why)"
        case .partial(let parts)?: problem = "What changed is incomplete: " + parts.map(\.rawValue).joined(separator: ", ") + " could not be read."
        case nil: problem = "What changed has not been read yet."
        default: break
        }
        var seen = Set<CaseMapNodeID>()
        for ch in feed?.newChanges ?? [] {
            guard let r = ch.record, let n = p.node(r), seen.insert(r).inserted else { continue }
            unseen.append(CaseMapBrief.Entry(node: r, text: n.title, why: "Changed since you last marked the changes as seen", basis: ch.kind.rawValue))
        }
        let review = p.nodes.filter { $0.review.awaitingReview && $0.kind != .action && $0.id.kind != .caseFile }.map {
            CaseMapBrief.Entry(node: $0.id, text: $0.title, why: $0.review.label, basis: $0.status.text)
        }
        let horizon = now.addingTimeInterval(Double(days) * 86_400)
        let due = p.nodes.filter { $0.workOpen == true && ($0.status.text.hasSuffix("overdue") || ($0.eventDate.map { $0 <= horizon } ?? false)) }
            .sorted { ($0.eventDate ?? .distantFuture, $0.id) < ($1.eventDate ?? .distantFuture, $1.id) }
            .map { CaseMapBrief.Entry(node: $0.id, text: $0.title, why: $0.status.text.hasSuffix("overdue") ? "Overdue" : "Due within \(days) days", basis: $0.status.text) }
        // Blocked: marked blocked, or waiting for work that is still open.
        let blocked = p.nodes.filter { n in
            guard n.workOpen == true else { return false }
            if n.workBlocked { return true }
            return p.links(of: n.id).contains { $0.from == n.id && $0.type == .dependsOn && p.node($0.to)?.workOpen == true }
        }.map { n in
            let waits = p.links(of: n.id).filter { $0.from == n.id && $0.type == .dependsOn }.compactMap { p.node($0.to) }.filter { $0.workOpen == true }
            return CaseMapBrief.Entry(node: n.id, text: n.title, why: waits.isEmpty ? "Marked blocked" : "Waits for: " + waits.map(\.title).joined(separator: "; "), basis: n.status.text)
        }
        let frames = (memory?.frames ?? []).map(\.anchor).filter { p.node($0) != nil }
        let sel = memory?.selectedNode.flatMap { p.node($0) != nil ? $0 : nil }
        return CaseReturnView(resumeFrames: frames, resumeSelection: sel, unseen: unseen, reviewRequired: review, due: due, blocked: blocked, feedProblem: problem)
    }
