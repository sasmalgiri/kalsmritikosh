public nonisolated struct CaseBriefing: Identifiable, Sendable, Equatable {
    public let id: UUID
    public let caseID: UUID
    public let title: String
    public let purpose: String?
    public let createdBy: String
    public let createdAt: Date
    public let frozenBy: String?
    public let frozenAt: Date?
    public let frozenFence: String?
    public let frozen: [CaseBriefingFrozenItem]?
    /// Set when the stored frozen state could not be read (it is never shown as an empty briefing).
    public let frozenProblem: String?
    public let withdrawnAt: Date?
    public let withdrawnReason: String?
    public var items: [CaseBriefingItem]
    public var isFrozen: Bool { frozenAt != nil }
    public var isActive: Bool { withdrawnAt == nil }
