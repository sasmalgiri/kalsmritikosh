//  Final completion instructions §3 — every advertised job has exactly one contract, the contracts
//  agree with the outcome matrix, and docs/JOB_CONTRACTS.md is generated from them (stale = failure).
//

import Foundation
import Testing
@testable import Kalsmritikosh

@Suite("Job contracts (all 168 advertised jobs)")
struct JobContractTests {

    @Test("Every advertised job has exactly one contract; studio contracts match the reviewed deliverable table")
    func coverage() {
        let advertised = JobOutcomeMatrixTests.advertised
        let contracted = JobContracts.all.map(\.job)
        #expect(Set(contracted).count == contracted.count, "a job has two contracts")
        #expect(Set(contracted) == Set(advertised.map(\.id)))
        #expect(Set(JobContracts.all.filter { $0.status == .studio }.map(\.job)) == Set(JobOutcomeMatrixTests.studioDeliverables.keys))
        for c in JobContracts.all {
            #expect(!c.question.isEmpty && !c.result.isEmpty && !c.policy.isEmpty && !c.human.isEmpty && !c.acceptance.isEmpty, "\(c.job) is incomplete")
        }
    }

    @Test("docs/JOB_CONTRACTS.md is the contract table")
    func documentIsGenerated() {
        let byID = Dictionary(uniqueKeysWithValues: JobOutcomeMatrixTests.advertised.map { ($0.id, $0) })
        func cell(_ s: String) -> String { s.replacingOccurrences(of: "|", with: "/") }
        let counts = Dictionary(grouping: JobContracts.all, by: \.status).mapValues(\.count)
        var out = """
        # Job contracts

        Generated by `JobContractTests.documentIsGenerated` from `Kalsmritikosh/Personas/JobContracts.swift`; do not hand-edit.
        One contract per advertised job (\(JobContracts.all.count)). **Status** is today's honest state of the job's result:
        *studio* — a specialist work product exists and is unit-verified, its journey not yet verified;
        *service* — the shared case service's result is the intended outcome, its journey not yet verified;
        *gap* — the intended result is not produced yet (the job returns only generic rows).

        | Status | Jobs |
        |---|---|
        | studio | \(counts[.studio] ?? 0) |
        | service | \(counts[.service] ?? 0) |
        | gap | \(counts[.gap] ?? 0) |

        ## What each result family does when input is missing, negative, inconclusive or denied

        | Family | Behaviour |
        |---|---|

        """
        for f in JobResultFamily.allCases { out += "| \(f.rawValue) | \(cell(f.whenIncomplete)) |\n" }
        let personas = JobOutcomeMatrixTests.advertised.map(\.persona).reduce(into: [String]()) { if !$0.contains($1) { $0.append($1) } }
        for persona in personas {
            let name = persona.replacingOccurrences(of: "com.kalsmritikosh.persona.", with: "")
            out += "\n## \(name)\n\n| Job | Title | Status | Family | Question | Required result | Method / policy | Human judgement | Acceptance |\n|---|---|---|---|---|---|---|---|---|\n"
            for c in JobContracts.all where byID[c.job]?.persona == persona {
                out += "| `\(c.job)` | \(cell(byID[c.job]?.title ?? "")) | \(c.status.rawValue) | \(c.family.rawValue) | \(cell(c.question)) | \(cell(c.result)) | \(cell(c.policy)) | \(cell(c.human)) | \(cell(c.acceptance)) |\n"
            }
        }
        Attachment.record(out, named: "JOB_CONTRACTS.md")
        let path = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("docs/JOB_CONTRACTS.md")
        let committed = (try? String(contentsOf: path, encoding: .utf8)) ?? ""
        if committed != out {
            Issue.record(Comment(rawValue: "docs/JOB_CONTRACTS.md is stale — replace it with:\n" + out))
        }
    }
}
